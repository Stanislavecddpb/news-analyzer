"""Базовая обработка русскоязычного текста: токенизация, нормализация, стемминг.

Модуль намеренно не тянет тяжёлых зависимостей (pymorphy2, spaCy, transformers),
чтобы прототип запускался «из коробки». Используется упрощённый стеммер по мотивам
алгоритма Snowball (Porter) для русского языка: он отсекает наиболее частотные
словоизменительные окончания, чего достаточно для сопоставления со словарём
тональности и для построения признаков кластеризации.

В production этот слой заменяется на pymorphy2 / Natasha (лемматизация) или на
эмбеддинги предложений — интерфейс (`normalize`, `tokenize`) при этом сохраняется.
"""

from __future__ import annotations

import re
from functools import lru_cache
from typing import Iterable

# Гласные русского алфавита — нужны для определения «области» стемминга (region RV).
_VOWELS = set("аеиоуыэюяё")

# Токен — последовательность русских/латинских букв и цифр. Дефис сохраняем внутри слова.
_TOKEN_RE = re.compile(r"[а-яёa-z0-9]+(?:-[а-яёa-z0-9]+)*", re.IGNORECASE)

# Минимальный стоп-список: служебные слова, не несущие тематической нагрузки.
# Частицы отрицания (не, нет, без, ни) сознательно НЕ включены — они нужны
# модулю тональности для обработки инверсии.
STOPWORDS: frozenset[str] = frozenset(
    """
    и в во на с со к ко о об от до за из изо у про для по при над под между
    а но или либо что чтобы как так это этот эта эти тот та те же бы ли уж
    был была были быть есть будет будут он она оно они мы вы ты я его ее их
    также тоже еще уже только даже там тут вот всё все всех весь вся
    год года году лет день дня сообщает сообщил передает заявил по словам
    """.split()
)

# Окончания, отсекаемые стеммером. Порядок важен: сначала длинные, потом короткие.
_PERFECTIVE_GERUND = (
    "ившись", "ывшись", "вшись", "ивши", "ывши", "вши", "ив", "ыв", "в",
)
_ADJECTIVE = (
    "ыми", "ими", "ого", "его", "ому", "ему", "ыми", "ыми", "ая", "яя", "ою",
    "ею", "ое", "ее", "ый", "ий", "ой", "ем", "им", "ым", "ом", "их", "ых",
    "ую", "юю", "ая", "яя", "ою", "ею",
)
_VERB = (
    "айте", "яйте", "ейте", "уйте", "ишь", "ете", "йте", "ешь", "нно", "ете",
    "ило", "ыло", "ено", "ует", "уют", "ит", "ыт", "ат", "ят", "ал", "ял",
    "ила", "ыла", "ена", "ейте", "уйте", "ите", "или", "ыли", "ей", "уй", "ил",
    "ыл", "им", "ым", "ен", "ило", "ыло", "ено", "ят", "ует", "уют", "ит",
    "ыт", "ан", "ян", "ло", "но", "ет", "ют", "ны", "ть", "ешь", "нно",
)
_NOUN = (
    "иями", "ями", "ами", "ией", "иям", "ием", "иях", "ев", "ов", "ие", "ье",
    "еи", "ии", "ей", "ой", "ий", "ям", "ем", "ам", "ом", "ах", "ях", "ью",
    "ия", "ье", "и", "й", "о", "у", "е", "ы", "ь", "а", "я", "ю",
)


def _strip_one(word: str, endings: Iterable[str], min_stem: int = 3) -> tuple[str, bool]:
    """Отсекает первое подходящее окончание, не укорачивая основу короче min_stem."""
    for end in sorted(endings, key=len, reverse=True):
        if word.endswith(end) and len(word) - len(end) >= min_stem:
            return word[: -len(end)], True
    return word, False


@lru_cache(maxsize=100_000)
def stem(word: str) -> str:
    """Упрощённый стеммер русского слова.

    Последовательно пытается отсечь деепричастные, глагольные, прилагательные
    и именные окончания. Кэшируется, т.к. в новостных текстах высокая повторяемость.
    """
    word = word.lower().replace("ё", "е")
    if len(word) <= 3 or not any(ch in _VOWELS for ch in word):
        return word

    word, changed = _strip_one(word, _PERFECTIVE_GERUND)
    if not changed:
        word, changed = _strip_one(word, _ADJECTIVE)
    if not changed:
        word, changed = _strip_one(word, _VERB)
    if not changed:
        word, _ = _strip_one(word, _NOUN)

    # Финальная зачистка: мягкий знак и удвоенная «нн» на конце основы.
    if word.endswith("ь"):
        word = word[:-1]
    return word


def tokenize(text: str) -> list[str]:
    """Разбивает текст на токены в нижнем регистре (буквы/цифры/дефис)."""
    return _TOKEN_RE.findall(text.lower().replace("ё", "е"))


def normalize(text: str, *, drop_stopwords: bool = True) -> list[str]:
    """Токенизация → отсев стоп-слов → стемминг. Возвращает список основ."""
    out: list[str] = []
    for tok in tokenize(text):
        if tok.isdigit():
            continue
        if drop_stopwords and tok in STOPWORDS:
            continue
        out.append(stem(tok))
    return out
