def _build_stemmed(raw: dict[str, float]) -> dict[str, float]:
    """Стеммирует ключи словаря; многословные термы оставляет как есть (матчатся по подстроке)."""
    out: dict[str, float] = {}
    for word, weight in raw.items():
        if " " in word:
            out[word] = weight
        else:
            out[stem(word)] = weight
    return out


